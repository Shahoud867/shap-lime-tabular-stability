W = {'0': 'Zero', '1': 'One', '2': 'Two', '3': 'Three', '4': 'Four', '5': 'Five', '6': 'Six', '7': 'Seven', '8': 'Eight', '9': 'Nine'}
macro = lambda k: re.sub(r'\d', lambda m: W[m.group(0)], k)

def esc(s):
    s = str(s if s is not None else '')
    rep = {'\\': r'\textbackslash{}', '{': r'\{', '}': r'\}', '$': r'\$', '&': r'\&', '%': r'\%', '#': r'\#', '_': r'\_', '^': r'\^{}', '~': r'\textasciitilde{}',
           '|': r'\textbar{}', '"': r'\textquotedbl{}', '<': r'\textless{}', '>': r'\textgreater{}', '–': '--', '—': '---', '‘': "`", '’': "'",
           '“': "``", '”': "''", '≤': r'$\le$', '≥': r'$\ge$', '±': r'$\pm$', '×': r'$\times$', '→': r'$\rightarrow$', 'ρ': r'$\rho$',
           'σ': r'$\sigma$', 'ε': r'$\varepsilon$', '≈': r'$\approx$', '−': '-', ' ': ' ', '‐': '-', '‑': '-', '₂': r'\textsubscript{2}'}
    out = ''.join(rep.get(ch, ch) for ch in s)
    return out.replace('/', r'/\allowbreak{}').replace(r'\_', r'\_\allowbreak{}')
def tt(s):
    return r'{\ttfamily\scriptsize ' + esc(s).replace(' OR ', r' OR\allowbreak{} ').replace(' AND ', r' AND\allowbreak{} ').replace(r'\textbar{}', r'\textbar{}\allowbreak{}') + '}'

# counts
cc = dict(C)
