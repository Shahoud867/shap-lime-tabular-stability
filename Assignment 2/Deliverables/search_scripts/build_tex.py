# Appendix C: extraction tables
def au(r):
    a = r['authors'] or []
    sur = lambda x: x.split()[-1] if x.split() else x
    return (sur(a[0]) + ' et al.') if len(a) > 2 else ' \\& '.join(esc(sur(x)) for x in a) if a else 'Anon.'
TY = {'journal': 'Journal', 'conference': 'Conference', 'workshop': 'Workshop', 'preprint': 'Preprint'}
L = [r'\begin{longtable}{@{}P{1.55cm}P{2.9cm}P{4.5cm}P{3.2cm}P{3.4cm}P{4.6cm}P{3.6cm}@{}}', r"\caption{Data extraction (part 1). `Not reported' marks items the paper does not report.}\label{tab:ext1}\\",
     r'\toprule Study & Problem / aim & Method & Dataset(s) & Evaluation & Key findings & Venue; peer review \\ \midrule \endfirsthead', r'\toprule Study & Problem / aim & Method & Dataset(s) & Evaluation & Key findings & Venue; peer review \\ \midrule \endhead', r'\bottomrule \endfoot']
