# Appendix B: full-text screening sheet
fc = {x['uid']: x for x in d['ftc']}; fc.update({(x.get('cid') or x.get('uid')): x for x in d['ftc_chase']}); fc.update({x['uid']: x for x in d['ftc_supp']})
