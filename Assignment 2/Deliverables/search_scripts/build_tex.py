cc['knownCs'] = sum(r[-2] == 'No' and r[-1] == 'Yes' for r in SL['validation']); cc['knownAll'] = cc['knownDb'] + cc['knownCs']
for k, v in cod['counts'].items(): cc['map' + k.replace('_', '')] = v
for q, v in cod['rq'].items(): cc['rq' + q[-1]] = v
qs = [r['qa_pct'] for r in M]
cc['qaMean'] = round(sum(qs) / len(qs), 1); cc['qaHigh'] = sum(x >= 80 for x in qs); cc['qaMod'] = sum(60 <= x < 80 for x in qs); cc['qaLow'] = sum(x < 60 for x in qs)
cc['dualPool'] = C['dbAllScreened']; cc['dualN'] = round(0.15 * C['dbAllScreened']); cc['dualPct'] = round(100 * cc['dualN'] / C['dbAllScreened'], 1)
with open(os.path.join(R, 'counts.tex'), 'w', encoding='utf8') as f:
    f.write('% generated by build_tex.py from the review data; do not edit by hand\n')
    for k, v in cc.items(): f.write(f'\\newcommand{{\\{macro(k)}}}{{{v}}}\n')

